# Программа применяет рекурсию для нахождения
# НОД двух чисел


def main():
    # Получить два числа
    num1 = int(input("Введите целое число: "))
    num2 = int(input("Введите целое число: "))

    # Показать НОД
    print(f"Наибольший общий делитель\nэтих двух числе равен {gcd(num1, num2)}.")


# Функция возвращает НОД
# двух чисел
def gcd(x, y):
    if x % y == 0:
        return y
    else:
        return gcd(x, x % y)


if __name__ == "__main__":
    main()
