# Программа демонстрирует рекурсивную функцию

def main():
    # Передаем аргументом 5 в функцию
    # мы сообщаем ей, что нужно показать сообщение
    # 5 раз
    message(5)

def message(times):
    if times > 0:
        print('Это рекурсивная функция')
        message(times - 1)

if __name__ == '__main__':
    main()