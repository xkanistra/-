# Функция раздет заданное кол-во карт 
def deal_cards(deck):
    logging.debug(f'Функция deal_cards приняла словарь deck без ошибок.\n')
    # Копируем список через метод copy, короче и понятнее код
    current_deck = deck.copy()

    # Ловим исключения если пользователь введет не число
    try:
        # Получить кол-во карт для раздачи
        player_1 = int(input('Сколько карт раздать 1 игроку? '))
        player_2 = int(input('Сколько карт раздать 2 игроку? '))
    except ValueError:
        logging.error(f'Пользователь ввел не верное значение в переменной.')
        print("Ошибка: введите число!")
        return
    
    # Списки которые будут накапливать в себе уже использованные в игре карты
    hand_value_pl1 = []
    hand_value_pl2 = []

    # 2 части отвечающие за раздачу карт
    print('\n--- Карты Игрока 1 ---')
    # Итерации цикла корректируются кол-вом выбранных карт пользователем
    for _ in range(player_1):
        # Условие проверяет, если в копии колоды нет карт, то программа завершается
        if not current_deck:
            print("Колода пуста!")
            logging.debug(f'Раздача прервана: колода пуста.')
            break
        
        # Присваиваем значение карты
        card = random.choice(list(current_deck.keys()))
        print(f'Выпала: {card}')
        
        # Добавляем выпавшую карту в список и после этого удаляем её из словаря через pop
        hand_value_pl1.append(current_deck[card])
        current_deck.pop(card) 

    print('\n--- Карты Игрока 2 ---')
    for _ in range(player_2):
        if not current_deck:
            print("Колода пуста!")
            logging.debug(f'Программа завершена.')
            break
            
        card = random.choice(list(current_deck.keys()))
        print(f"Выпала: {card}")
        
        hand_value_pl2.append(current_deck[card])
        current_deck.pop(card)

    # Считаем итоговые очки с умной логикой Тузов
    score1 = calculate_score(hand_value_pl1)
    score2 = calculate_score(hand_value_pl2)

    print(f'\n=== ИТОГИ ===')
    print(f'Сумма карт Игрока 1: {score1}')
    print(f'Сумма карт Игрока 2: {score2}')

    # Определяем победителя по строгим правилам
    if score1 > 21 and score2 > 21:
        print("Ничья! Оба игрока перебрали (больше 21).")
    elif score1 > 21:
        print("🏆 Игрок 2 победил! (Игрок 1 перебрал)")
    elif score2 > 21:
        print("🏆 Игрок 1 победил! (Игрок 2 перебрал)")
    elif score1 > score2:
        print("🏆 Игрок 1 победил!")
    elif score2 > score1:
        print("🏆 Игрок 2 победил!")
    else:
        print("Ничья! Одинаковое количество очков.")
        
    logging.debug(f"Осталось карт в колоде: {len(current_deck)}")


# Функция получает список значений и считает итоговую сумму
def calculate_score(hand_values):
    logging.debug(f'Функция calculate_score приняла список hand_values без ошибок.\n')
    # Считаем сумму динамически превращая туз в 11 
    # Переменная принимает в себя список выпавших значений и суммирует через инструкцию sum
    total = sum(hand_values)
    # Переменная которой присваивается значнение один для умного подсчета тузов
    aces_count = hand_values.count(1)

    # Условие умного учета Тузов
    if aces_count > 0 and total + 10 <= 21:
        total += 10
    logging.debug(f'Функция успешно рассчитала очки\n')
    return total

