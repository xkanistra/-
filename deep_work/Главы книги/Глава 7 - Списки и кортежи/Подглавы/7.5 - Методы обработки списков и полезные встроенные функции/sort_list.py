# Программа демонстрирует работу метода sort

my_list = [9, 2, 3, 5, 6, 4, 8, 10]
print(f'Первоначальный порядок: {my_list}')

my_list.sort()
print(f'Отсортированный порядок: {my_list}')

list_name = ['Юзер', 'Лох', 'Кирилл', 'Стас']
print(f'Первоначальный порядок: {list_name}')
list_name.sort()
print(f'Отсортированный порядок: {list_name}')