# Функция расчета простых чисел
import math
def get_prime(n):
    if n < 2: # отрицательные числа игнорируем, 0 и 1 не простые
        return False

    if n == 2: # 2 - простое число
        return True
    if n % 2 == 0: # четные числа больше 2 не простые
        return False

    # проверяем делимость только для кандидатов до sqrt(n)
    limit = math.isqrt(n)
    # проверяем делимость только на нечетные числа, начиная с 3
    for i in range(3, limit + 1, 2): 
        if n % i == 0:
            # найден делитель, число не простое
            return False

    # делителей не найдено, число простое
    return True