# Запрашивает у пользователя целое число с помощью input(prompt).
# В цикле повторяет запрос, пока пользователь не введёт корректное целое число.
# При ошибке ValueError (нечисловой ввод) выводит предупреждение и продолжает цикл.
# Возвращает валидированное целое число.
def ask_int(prompt: str) -> int:
    # Безопасный запрос числа. Легко заменить на bot.send_message() + FSM
    while True:
        try:
            val = int(input(prompt))
            return val
        except ValueError:
            print("⚠️ Введите целое число.")

# Запрашивает подтверждение «Да/Нет» у пользователя;
# Нормализует ввод: приводит к нижнему регистру и убирает пробелы (strip().lower()).
# Принимает несколько вариантов ответа.
# При некорректном вводе повторяет запрос с подсказкой.
# Возвращает True или False.
def ask_yes_no(prompt: str) -> bool:
    while True:
        ans = input(prompt).strip().lower()
        if ans in ('1', 'да', 'y'): return True
        if ans in ('2', 'нет', 'n'): return False
        print("⚠️ Введите 1 (Да) или 2 (Нет)")